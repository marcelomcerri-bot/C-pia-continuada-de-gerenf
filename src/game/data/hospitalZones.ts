export function getZoneByCoords(col: number, row: number): HospitalZone | undefined {
  return HOSPITAL_ZONES.find(
    (z) => col >= z.col1 && col <= z.col2 && row >= z.row1 && row <= z.row2
  );
}

export function getZoneById(id: string): HospitalZone | undefined {
  return HOSPITAL_ZONES.find((z) => z.id === id);
}

export function getZoneByTileId(tileId: number): HospitalZone | undefined {
  return HOSPITAL_ZONES.find((z) => z.tileId === tileId);
}
